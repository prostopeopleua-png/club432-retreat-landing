/** Результат підрахунку по одній із двох шкал */
export type RayScore = {
  ray: RayId;
  /** Скільки обраних цінностей потрапило в цей Промінь */
  hits: number;
  /** Скільки їх мало б потрапити випадково, з огляду на розмір списку */
  expected: number;
  /** hits / expected. Більше за 1 означає «обрано частіше, ніж випадково» */
  lift: number;
  values: string[];
};

export type RayReading = {
  /** Промінь, чиї відмінні риси людина обрала непропорційно часто */
  resonance: RayScore | null;
  /** Промінь, чиї якості набуття вона обрала непропорційно часто */
  need: RayScore | null;
  /** true, коли відгук і потреба збіглися: сигнал сильний */
  aligned: boolean;
  /** Повні таблиці, якщо треба показати розподіл */
  allResonance: RayScore[];
  allNeed: RayScore[];
};

/** Менше за це число влучань не оголошуємо Променем: на одному слові
 *  висновку не будують, краще нічого не сказати, ніж сказати навмання. */
const MIN_HITS = 2;

/**
 * Читання Променів за обраною десяткою.
 *
 * ВАЖЛИВО про нормування. Слова розподілені по Променях нерівно: у П'ятого
 * серед відмінних рис їх удвічі більше, ніж у Третього, бо таким є
 * першоджерело, а не наш вибір. Якби ми рахували сирі влучання, П'ятий
 * вигравав би просто частотою. Тому рахуємо lift: у скільки разів людина
 * обрала цей Промінь частіше, ніж вийшло б випадково.
 *
 * @param picked  десятка, яку обрала людина
 * @param all     повний список цінностей, потрібен для базових частот
 */
export const readRays = (
  picked: { v: string; res?: RayId[]; need?: RayId[] }[],
  all: { v: string; res?: RayId[]; need?: RayId[] }[],
): RayReading => {
  const tally = (key: "res" | "need"): RayScore[] => {
    const base = new Map<RayId, number>();
    for (const item of all) {
      for (const ray of item[key] || []) base.set(ray, (base.get(ray) || 0) + 1);
    }

    const hit = new Map<RayId, string[]>();
    for (const item of picked) {
      for (const ray of item[key] || []) hit.set(ray, [...(hit.get(ray) || []), item.v]);
    }

    return [...hit.entries()]
      .map(([ray, values]) => {
        const expected = ((base.get(ray) || 0) / (all.length || 1)) * picked.length;
        return {
          ray,
          hits: values.length,
          expected: Number(expected.toFixed(2)),
          lift: expected > 0 ? Number((values.length / expected).toFixed(2)) : 0,
          values,
        };
      })
      .sort((a, b) => b.lift - a.lift || b.hits - a.hits || a.ray - b.ray);
  };

  const allResonance = tally("res");
  const allNeed = tally("need");
  const top = (list: RayScore[]) => list.find((x) => x.hits >= MIN_HITS) || null;
  const resonance = top(allResonance);
  const need = top(allNeed);

  return {
    resonance,
    need,
    aligned: Boolean(resonance && need && resonance.ray === need.ray),
    allResonance,
    allNeed,
  };
};
